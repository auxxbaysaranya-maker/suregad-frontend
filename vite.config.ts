import { defineConfig, loadEnv } from "vite";
import react from "@vitejs/plugin-react";
import tailwindcss from "@tailwindcss/vite";
import { VitePWA } from "vite-plugin-pwa";
import fs from "fs";
import path from "path";

/**
 * Generates public/firebase-messaging-sw.js from the VITE_FIREBASE_* values (public web config only).
 * The server sends data-only messages, so this worker decides how a notification looks and where a click goes.
 */
function writeFirebaseMessagingWorker(env: Record<string, string>, base: string) {
  const config = {
    apiKey: env.VITE_FIREBASE_API_KEY || "",
    authDomain: env.VITE_FIREBASE_AUTH_DOMAIN || "",
    projectId: env.VITE_FIREBASE_PROJECT_ID || "",
    messagingSenderId: env.VITE_FIREBASE_MESSAGING_SENDER_ID || "",
    appId: env.VITE_FIREBASE_APP_ID || "",
  };
  const source = `// Generated by vite.config.ts — edit the template there, not this file.
importScripts("https://www.gstatic.com/firebasejs/12.6.0/firebase-app-compat.js");
importScripts("https://www.gstatic.com/firebasejs/12.6.0/firebase-messaging-compat.js");
const BASE = ${JSON.stringify(base)};
if (${JSON.stringify(Boolean(config.apiKey && config.projectId && config.messagingSenderId))}) {
  firebase.initializeApp(${JSON.stringify(config)});
  firebase.messaging().onBackgroundMessage((payload) => {
    const data = payload.data || {};
    return self.registration.showNotification(data.title || "SureGad", {
      body: data.body || "",
      icon: BASE + "brand/icon-192.png",
      badge: BASE + "brand/favicon-64.png",
      tag: data.tag || "suregad",
      renotify: true,
      data: { url: data.url || self.location.origin + BASE },
    });
  });
}
self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  const url = (event.notification.data && event.notification.data.url) || self.location.origin + BASE;
  event.waitUntil(
    clients.matchAll({ type: "window", includeUncontrolled: true }).then((windows) => {
      const target = new URL(url);
      for (const client of windows) {
        if (new URL(client.url).origin === target.origin && "focus" in client) {
          return client.focus().then((focused) => (focused && "navigate" in focused ? focused.navigate(url) : focused));
        }
      }
      return clients.openWindow(url);
    }),
  );
});
`;
  fs.writeFileSync(path.resolve(__dirname, "public/firebase-messaging-sw.js"), source);
}

export default defineConfig(({ mode }) => {
  const env = loadEnv(mode, __dirname, "");
  // "/" locally and on suregad.in.
  const base = env.VITE_BASE_PATH || "/";
  writeFirebaseMessagingWorker(env, base);
  return {
  base,
  plugins: [
    react(),
    tailwindcss(),
    VitePWA({
      // "prompt": a new deploy shows "Update available" with an Update button.
      registerType: "prompt",
      injectRegister: false,
      includeAssets: ["brand/favicon-64.png", "brand/apple-touch-icon.png", "brand/logo.png", "brand/mark.png"],
      manifest: {
        id: base,
        name: "SureGad",
        short_name: "SureGad",
        description: "Buy and sell verified used and refurbished phones and laptops.",
        theme_color: "#3a3fe0",
        background_color: "#f7f6fc",
        display: "standalone",
        start_url: base,
        scope: base,
        icons: [
          { src: "brand/icon-192.png", sizes: "192x192", type: "image/png", purpose: "any" },
          { src: "brand/icon-512.png", sizes: "512x512", type: "image/png", purpose: "any" },
          { src: "brand/icon-512.png", sizes: "512x512", type: "image/png", purpose: "maskable" },
        ],
      },
      devOptions: { enabled: false },
      workbox: {
        importScripts: [`${base}push-handler.js`],
        navigateFallback: `${base}index.html`,
        navigateFallbackDenylist: [/\/api\//],
        cleanupOutdatedCaches: true,
        // Take control on first install so later updates can reload the page; updates still wait for "Update now".
        clientsClaim: true,
        maximumFileSizeToCacheInBytes: 4 * 1024 * 1024,
        runtimeCaching: [
          {
            urlPattern: ({ url }) => url.pathname.startsWith("/api/") || url.pathname.startsWith("/socket.io"),
            handler: "NetworkOnly",
          },
        ],
      },
    }),
  ],
  resolve: {
    alias: {
      "@": path.resolve(__dirname, "src"),
    },
  },
  server: {
    port: 5173,
    proxy: {
      "/api": "http://localhost:4000",
      "/media": "http://localhost:4000",
      "/socket.io": { target: "http://localhost:4000", ws: true },
    },
  },
};
});
